# --- Функции ---

def replace_terms_in_text(text, terms_map):
    """Заменяет все термины в тексте по словарю."""
    for original, fake in terms_map.items():
        text = re.sub(
            r'\b' + re.escape(original) + r'\b',
            fake,
            text,
            flags=re.IGNORECASE
        )
    return text

def transform_filename(filename, terms_map):
    """
    Преобразует имя файла, заменяя части имени согласно TERMS_MAP.
    Сохраняет расширение файла.
    """
    # Разделяем имя и расширение
    name_part, ext_part = os.path.splitext(filename)
    
    # Применяем замены к имени файла
    transformed_name = name_part
    for original, fake in terms_map.items():
        transformed_name = re.sub(
            re.escape(original),
            fake,
            transformed_name,
            flags=re.IGNORECASE
        )
    
    # Возвращаем полное имя с расширением
    return transformed_name + ext_part

def process_file(input_path, output_path, terms_map):
    """Читает файл, заменяет термины, сохраняет в выходную папку."""
    try:
        # Читаем входной файл
        with open(input_path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        
        # Применяем замены в тексте
        modified_content = replace_terms_in_text(content, terms_map)
        
        # Создаём родительскую папку для выходного файла
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Записываем результат
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(modified_content)
        print(f"Обработано: {input_path} → {output_path}")
    except Exception as e:
        print(f"Ошибка при обработке {input_path}: {e}")

def main():
    # Обходим все файлы в input_dir рекурсивно
    for root, dirs, files in os.walk(INPUT_DIR):
        for file in files:
            if file.endswith('.md'):
                # Формируем полный путь к входному файлу
                input_path = Path(root) / file
                
                # Получаем относительный путь (без файла) от INPUT_DIR
                relative_dir = input_path.relative_to(INPUT_DIR).parent
                
                # Преобразуем имя файла по словарю замен
                new_filename = transform_filename(file, TERMS_MAP)
                # Формируем полный путь к выходному файлу с новым именем
                output_path = Path(OUTPUT_DIR) / relative_dir / new_filename
                
                # Обрабатываем файл (замена текста + сохранение)
                process_file(input_path, output_path, TERMS_MAP)

    print("\nГотово! Все файлы обработаны.")


# --- Запуск ---
if __name__ == "__main__":
    main()